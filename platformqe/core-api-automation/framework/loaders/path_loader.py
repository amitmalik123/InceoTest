"""
Path Loader

Centralized path management utility for the framework.
Provides simple function-based API with automatic project root detection.
"""

import os
from pathlib import Path
from typing import Optional, List
from framework.common.logger import get_logger

logger = get_logger(__name__)

# Project root detection (auto-detect once at module load)
_PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent


def get_project_root() -> Path:
    """
    Get the project root directory.
    
    Returns:
        Path object pointing to project root
    """
    return _PROJECT_ROOT


def get_project_path(*parts) -> Path:
    """
    Get absolute path relative to project root.
    
    Args:
        *parts: Path components to join
    
    Returns:
        Absolute Path object
    
    Example:
        >>> get_project_path('templates', 'TestCase_Template.json')
        Path('/path/to/project/templates/TestCase_Template.json')
    """
    return _PROJECT_ROOT.joinpath(*parts)


def path_exists(*parts) -> bool:
    """
    Check if path exists relative to project root.
    
    Args:
        *parts: Path components to check
    
    Returns:
        True if path exists, False otherwise
    
    Example:
        >>> path_exists('templates', 'TestCase_Template.json')
        True
    """
    return get_project_path(*parts).exists()


def list_directory(*parts) -> List[Path]:
    """
    List files/directories in path relative to project root.
    
    Args:
        *parts: Path components to directory
    
    Returns:
        List of Path objects in the directory
    
    Example:
        >>> list_directory('testcases_autogenerated')
        [Path('...'), Path('...')]
    """
    path = get_project_path(*parts)
    if path.is_dir():
        return list(path.iterdir())
    return []


def find_files(pattern: str, base_dir: Optional[str] = None) -> List[Path]:
    """
    Recursively find files matching pattern.
    
    Args:
        pattern: Glob pattern (e.g., '*.json', '**/*.csv')
        base_dir: Base directory relative to project root (None = project root)
    
    Returns:
        List of matching Path objects
    
    Example:
        >>> find_files('*.json', 'testcases_autogenerated')
        [Path('testcases_autogenerated/swagger/tc001.json'), ...]
    """
    if base_dir is None:
        base = _PROJECT_ROOT
    else:
        base = get_project_path(base_dir)
    
    return list(base.rglob(pattern))


def resolve_testdata_path(relative_path: str) -> str:
    """
    Resolve path relative to testdata directory.
    
    Args:
        relative_path: Path relative to testdata/ or absolute path
    
    Returns:
        Absolute path (testdata/ prefix added if relative)
    
    Example:
        >>> resolve_testdata_path('parties/testcases/tc001.json')
        'testdata/parties/testcases/tc001.json'
        >>> resolve_testdata_path('/abs/path/file.json')
        '/abs/path/file.json'
    """
    if os.path.isabs(relative_path):
        return relative_path
    
    return os.path.join('testdata', relative_path)


def ensure_file_exists(file_path: str, error_msg: Optional[str] = None) -> bool:
    """
    Check if file exists and log error if not.
    
    Args:
        file_path: Path to check
        error_msg: Custom error message (optional)
    
    Returns:
        True if file exists, False otherwise
    
    Raises:
        FileNotFoundError: If error_msg is provided and file doesn't exist
    """
    if os.path.exists(file_path):
        return True
    
    if error_msg:
        logger.error(error_msg)
        raise FileNotFoundError(error_msg)
    else:
        logger.warning(f"File not found: {file_path}")
        return False


def ensure_dir_exists(dir_path: str) -> str:
    """
    Ensure directory exists, create if not.
    
    Args:
        dir_path: Directory path to create
    
    Returns:
        Directory path (for chaining)
    """
    os.makedirs(dir_path, exist_ok=True)
    return dir_path


def resolve_path_with_fallback(paths: list, base_dir: str = 'testdata') -> Optional[str]:
    """
    Try multiple paths and return first one that exists.
    
    Args:
        paths: List of paths to try
        base_dir: Base directory for relative paths
    
    Returns:
        First existing path or None
    
    Example:
        >>> resolve_path_with_fallback(['file.json', 'backup/file.json'])
        'testdata/backup/file.json'  # if first doesn't exist
    """
    for path in paths:
        if not os.path.isabs(path):
            path = os.path.join(base_dir, path)
        
        if os.path.exists(path):
            logger.debug(f"Resolved path: {path}")
            return path
    
    logger.warning(f"None of the paths exist: {paths}")
    return None


def get_file_extension(file_path: str) -> str:
    """
    Get file extension (lowercase, without dot).
    
    Args:
        file_path: Path to file
    
    Returns:
        File extension without dot (e.g., 'json', 'sql', 'csv')
    """
    _, ext = os.path.splitext(file_path)
    return ext.lstrip('.').lower()


def is_json_file(file_path: str) -> bool:
    """Check if file path ends with .json"""
    return file_path.lower().endswith('.json')


def is_sql_file(file_path: str) -> bool:
    """Check if file path ends with .sql"""
    return file_path.lower().endswith('.sql')


def is_csv_file(file_path: str) -> bool:
    """Check if file path ends with .csv"""
    return file_path.lower().endswith('.csv')
