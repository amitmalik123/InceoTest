    def validation_Errors_for_Mandatory_Fields(self, firstName, lastName, email):
        self.page.saveButton.click()
        self.page.wait_for_timeout(2000)
        expect(self.page.lastNameError).to_contain_text("Complete this field.")
        self.page.wait_for_timeout(2000)
        expect(self.page.emailError).to_contain_text("Complete this field.")
        self.page.wait_for_timeout(2000)
        expect(self.page.leadSourceError).to_contain_text("Complete this field.")
        self.page.wait_for_timeout(2000)
        self.page.lastNameInput.fill(lastName)
        self.page.wait_for_timeout(1000)
        self.page.emailInput.fill(email)
        self.page.wait_for_timeout(2000)
        # Make sure the Lead Source combobox is in view; after a failed save the page
        # often scrolls to the first error field and the dropdown can be off-screen,
        # which causes the option list never to render.
        #self.page.leadSourceDropdown.scroll_into_view_if_needed()
        #self.page.leadSourceDropdown.wait_for(state="visible", timeout=5000)

        # Open the dropdown and verify the option list actually appeared.
        # Retry up to 3 times because in this validation flow the first click
        # sometimes opens-and-immediately-closes the listbox.
        listbox = self.page.locator("div[aria-label='Lead Source'][role='listbox']")
        for attempt in range(3):
            self.page.leadSourceDropdown.click()
            try:
                listbox.wait_for(state="visible", timeout=3000)
                self.page.leadSourceDropdown2.wait_for(state="visible", timeout=3000)
                break
            except Exception:
                if attempt == 2:
                    raise
                self.page.wait_for_timeout(500)
        self.page.leadSourceDropdown2.click()
        self.page.saveButton.click() 
        self.page.wait_for_timeout(3000)
        expect(self.page.firstNameError).to_contain_text("Lead First Name is Required")
        self.page.firstNameInput.fill(firstName)
        self.page.cancelButton.click()


